"""常见餐具/份量的克重换算。

## 为什么需要

「一碗米饭等于多少运动」—— 用户给的是「一碗」不是「150克」。
系统必须知道一碗 ≈ 多少克，否则算不出来。

这与「斤=500g」是同一类问题（单位换算），
但更隐蔽：餐具份量是**经验值**，各家差异很大，
所以这里集中定义并写明依据，而不是散落在各处。
"""

from __future__ import annotations

# 常见「一份」的克重。按中国居民常见家用餐具估算。
# 依据：《中国食物成分表》与常见餐饮标准的「份」定义。
PORTION_GRAMS: dict[str, float] = {
    # 主食 —— 注意：这里只放**纯量词**，不要放「碗米饭」这类组合。
    # 「碗米饭」既是别名又是量词组合，会导致剥量词时把食物名一起剥掉。
    "小碗": 150.0,
    "大碗": 300.0,
    "碗": 200.0,          # 一标准饭碗（直径约 11cm）盛米饭
    "饭": 200.0,
    "个": 100.0,          # 一个鸡蛋/馒头
    "只": 100.0,
    "杯": 250.0,          # 一标准杯（马杯）
    "瓶": 500.0,          # 一瓶饮料
    "罐": 330.0,
    "听": 330.0,
    "袋": 200.0,
    "包": 100.0,
    "份": 200.0,
    "盘": 250.0,
    "块": 50.0,
    "片": 30.0,
    "根": 60.0,           # 一根玉米
    "盒": 400.0,
}

# 别名 → 标准键
_ALIASES = {
    "小碗": "小碗",
    "大碗": "大碗",
    "米饭碗": "碗",
    "一碗": "碗",
    "一杯": "杯",
    "一瓶": "瓶",
    "一个": "个",
    "一只": "只",
    "一罐": "罐",
    "一盒": "盒",
    "一盘": "盘",
    "一份": "份",
    "一块": "块",
    "一片": "片",
    "一根": "根",
    "一袋": "袋",
    "一包": "包",
}


def lookup(text: str) -> tuple[str, float] | None:
    """从文本里找餐具量词，返回 (量词, 克重)。

    「一碗米饭」→ ("碗", 200.0)
    「两个鸡蛋」→ ("个", 100.0) × 2 由调用方处理
    """
    if not text:
        return None
    # 长别名优先，避免「碗米饭」被「碗」截胡
    for key in sorted(PORTION_GRAMS, key=len, reverse=True):
        if key in text:
            return key, PORTION_GRAMS[key]
    return None


def grams_from(text: str, default: float | None = None) -> float | None:
    """便捷函数：直接拿克重。"""
    got = lookup(text)
    return got[1] if got else default


def describe(key: str, grams: float) -> str:
    """给用户看的一句话：把克重换算说清楚，避免误解。"""
    return f"约 {grams:g} 克（按「{key}」的常见份量估算）"
